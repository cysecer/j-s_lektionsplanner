import { z } from "zod";
import { Difficulty, LessonStatus } from "@/generated/prisma/enums";
import {
  blockContentShape,
  optionalInt,
  participantsInOrder,
  participantsRangeIssue,
  responsibleSchema,
  uuidSet,
} from "@/lib/blocks/schema";
import { richTextSchema } from "@/lib/rich-text/schema";
import { displayName } from "@/lib/settings/schemas";
import { clockTimeSchema } from "./timing";

export const LESSON_LIMITS = { items: 80, coaches: 50 } as const;

const optionalText = (max: number) =>
  z.union([z.literal("").transform(() => null), z.null(), displayName(max)]);

/**
 * One program block placed in a lesson: a snapshot of the block's content
 * plus where it sits and who leads it. Ids are generated by the client so
 * the whole lesson can be saved as one document.
 */
export const lessonItemSchema = z
  .strictObject({
    id: z.uuid(),
    sectionId: z.uuid(),
    sourceBlockId: z.uuid().nullable(),
    modifiedLocally: z.boolean(),
    responsible: responsibleSchema,
    ...blockContentShape,
  })
  .refine(participantsInOrder, participantsRangeIssue);

export type LessonItemInput = z.output<typeof lessonItemSchema>;
export type LessonItemValues = z.input<typeof lessonItemSchema>;

export const lessonGeneralSchema = z
  .strictObject({
    title: displayName(150),
    authorName: displayName(100),
    date: z.iso.date({ message: "validation.date" }),
    teamId: z.uuid().nullable(),
    layoutId: z.uuid().nullable(),
    /** "HH:MM"; empty = no clock times. */
    startTime: z.union([z.literal("").transform(() => null), clockTimeSchema]),
    totalDurationMinutes: optionalInt(1, 1440),
    location: optionalText(120),
    ageMin: optionalInt(0, 120),
    ageMax: optionalInt(0, 120),
    groupSize: optionalText(60),
    difficulty: z.enum(Difficulty).nullable(),
    safety: richTextSchema.nullable(),
    goals: richTextSchema.nullable(),
    notes: richTextSchema.nullable(),
    presentCoachIds: uuidSet(LESSON_LIMITS.coaches),
    status: z.enum(LessonStatus),
  })
  .refine((l) => l.ageMin === null || l.ageMax === null || l.ageMin <= l.ageMax, {
    message: "validation.ageRange",
    path: ["ageMax"],
  });

export type LessonGeneralInput = z.output<typeof lessonGeneralSchema>;
export type LessonGeneralValues = z.input<typeof lessonGeneralSchema>;

/**
 * Saving a lesson sends the whole document. `baseVersion` is the
 * updatedAt the client started from; a newer version on the server means
 * someone else saved in between (no silent overwrite).
 */
export const lessonSaveSchema = z
  .strictObject({
    id: z.uuid(),
    baseVersion: z.iso.datetime(),
    lesson: lessonGeneralSchema,
    /** In display order; sortOrder is derived per section. */
    items: z.array(lessonItemSchema).max(LESSON_LIMITS.items),
  })
  .refine((s) => new Set(s.items.map((i) => i.id)).size === s.items.length, {
    message: "validation.invalid",
    path: ["items"],
  });

export type LessonSaveInput = z.output<typeof lessonSaveSchema>;

/** The first save of a new lesson: its content, no id or version yet. */
export const lessonDraftSchema = z
  .strictObject({
    lesson: lessonGeneralSchema,
    items: z.array(lessonItemSchema).max(LESSON_LIMITS.items),
  })
  .refine((s) => new Set(s.items.map((i) => i.id)).size === s.items.length, {
    message: "validation.invalid",
    path: ["items"],
  });
